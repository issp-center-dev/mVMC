"""Optimization of the OptTrans weights (vmc.out -o).

Six-site Hubbard ring (U = 4, half filling) with a two-site sublattice in f_ij,
generated by vmcdry.out from the StdFace input of data/HubbardChain with
NSROptItrStep = 100, then edited: no fixed translation projection
(NMPTrans 1, identity in qptransidx.def) and an optimized projection
qpopttrans.def = {identity, translation by one site} started from the
weights (1, 0).  The k = 0 ground state favours the translated term, so its
weight must grow during the SR optimization; if the OptTrans parameters are
not optimized it stays at its initial value 0.
"""
from __future__ import print_function

import os
import shutil
import subprocess
import sys

MODEL = "OptTrans_HubbardChain"


def main():
    rootdir = os.getcwd()
    source = os.path.join(rootdir, "data", MODEL)
    mpi_procs = os.environ.get("MVMC_MPI_PROCS")
    workdir = os.path.join(rootdir, "work", MODEL + ("_mpi" if mpi_procs else ""))
    if os.path.exists(workdir):
        shutil.rmtree(workdir)
    os.makedirs(workdir)
    for filename in os.listdir(source):
        if filename.endswith(".def"):
            shutil.copy2(os.path.join(source, filename), workdir)

    binary = os.path.join(rootdir, "..", "..", "src", "mVMC", "vmc.out")
    command = [binary, "-e", "-o", "namelist.def"]
    if mpi_procs:
        command = ["mpirun", "-np", mpi_procs] + command
    environment = os.environ.copy()
    environment["OMP_NUM_THREADS"] = "1"
    process = subprocess.run(command, cwd=workdir, env=environment,
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                             universal_newlines=True)
    var = os.path.join(workdir, "output", "zvo_var_001.dat")
    if process.returncode != 0 or not os.path.exists(var):
        print(process.stdout)
        return process.returncode or 1

    # each line of zvo_var_001.dat: 6 leading numbers, then (re, im, 0) per
    # parameter; the two OptTrans weights are the last two parameters
    with open(var) as f:
        rows = [line.split() for line in f if line.strip()]
    w0 = [float(r[-6]) for r in rows]
    w1 = [float(r[-3]) for r in rows]
    print("OptTrans weights after the last step: {:.4f} {:.4f}".format(w0[-1], w1[-1]))
    if len(rows) != 100:
        print("FAIL: expected 100 SR steps, got {}".format(len(rows)))
        return 1
    if any(abs(max(abs(a), abs(b)) - 1.0) > 1e-12 for a, b in zip(w0, w1)):
        print("FAIL: the weights are not normalized to max |w| = 1")
        return 1
    if w1[-1] < 0.5:
        print("FAIL: the weight of the translated term did not grow from 0")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
