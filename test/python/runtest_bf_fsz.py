def read_child_opt_rows(path):
    rows = []
    with open(path) as fp:
        for line in fp:
            cols = line.split()
            if len(cols) < 3:
                continue
            try:
                idx = int(cols[0])
                real = float(cols[1])
                imag = float(cols[2])
            except ValueError:
                continue
            rows.append((idx, real, imag))
    return rows


