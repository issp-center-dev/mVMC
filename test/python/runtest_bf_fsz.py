def spin_orbital_row(indices, nsite=4):
    row = []
    for index in indices:
        row.extend((index % nsite, index // nsite))
    return tuple(row)


def build_spin_changing_c2_rows(nsite=4):
    a, b, c, d = 0, nsite + 1, 2, nsite + 3
    classes = [
        (a, a, a, a),
        (a, a, a, b),
        (a, a, b, a),
        (a, a, b, b),
        (a, a, b, c),
        (a, b, a, b),
        (a, b, a, a),
        (a, b, a, c),
        (a, b, b, a),
        (a, b, c, a),
        (a, b, b, b),
        (a, b, b, c),
        (a, b, c, b),
        (a, b, c, c),
        (a, b, c, d),
    ]
    return [spin_orbital_row(indices, nsite=nsite) for indices in classes]


