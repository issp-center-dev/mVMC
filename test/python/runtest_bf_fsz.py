def run_vmc(rootdir, workdir, mpi_procs=None, init_path=None, extra_env=None):
    bin_to_test = os.path.join(rootdir, "..", "..", "src", "mVMC", "vmc.out")
    cmd = [bin_to_test, "-e", "namelist.def"]
    if init_path is not None:
        cmd.append(init_path)
    if mpi_procs:
        mpi_args = os.environ.get("MVMC_MPI_ARGS", "").split()
        cmd = ["mpirun"] + mpi_args + ["-np", mpi_procs] + cmd
    env = os.environ.copy()
    if extra_env is not None:
        env.update(extra_env)
    proc = subprocess.run(
        cmd,
        cwd=workdir,
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    with open(os.path.join(workdir, "vmc.log"), "w") as fp:
        fp.write(proc.stdout)
    return proc


