def build_stale_base_two_body_rows(nsite=4):
    general_rows = []
    contracted_rows = []

    # Cover every spin-conserving double hop so at least one general-path term
    # is active for every half-filled sample generated by this fixture.
    for s, t in ((0, 1), (1, 0)):
        for rj in range(nsite):
            for ri in range(nsite):
                if ri == rj:
                    continue
                for rl in range(nsite):
                    for rk in range(nsite):
                        if rk == rl:
                            continue
                        general_rows.append((ri, s, rj, s, rk, t, rl, t))

        # rk == rl dispatches to GreenFunc1BF_fsz after checking the density.
        # Listing all sites and hops guarantees an active contracted term after
        # the last active general term has overwritten global SlaterElmBF.
        for rk in range(nsite):
            for rj in range(nsite):
                for ri in range(nsite):
                    if ri != rj:
                        contracted_rows.append((ri, s, rj, s, rk, t, rk, t))

    return general_rows, contracted_rows


