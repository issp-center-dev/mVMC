def read_bffsz_profile_stats(path, source, kind):
    marker = "BF-FSZ {} {} stats".format(source, kind)
    with open(path) as fp:
        for line in fp:
            if marker not in line:
                continue
            fields = {}
            for token in line.split():
                if "=" in token:
                    key, value = token.split("=", 1)
                    fields[key] = value
            if not all(key in fields for key in ("calls", "mean", "max")):
                break
            return int(fields["calls"]), float(fields["mean"]), int(fields["max"])
    raise RuntimeError("{} was not found in {}".format(marker, path))


def read_bffsz_profile_hist_sum(path, source, kind):
    marker = "BF-FSZ {} {}".format(source, kind)
    with open(path) as fp:
        for line in fp:
            if marker not in line:
                continue
            values = []
            for token in line.split():
                if ":" not in token:
                    continue
                try:
                    values.append(int(token.rsplit(":", 1)[1]))
                except ValueError:
                    pass
            if values:
                return sum(values)
    raise RuntimeError("{} was not found in {}".format(marker, path))


def read_bffsz_pf_paths(path, source):
    marker = "BF-FSZ {} Pfaffian paths".format(source)
    with open(path) as fp:
        for line in fp:
            if marker not in line:
                continue
            values = {}
            for token in line.split():
                if ":" not in token:
                    continue
                key, value = token.rsplit(":", 1)
                try:
                    values[key] = int(value)
                except ValueError:
                    pass
            if all(key in values for key in ("optimized", "direct-full", "fallback")):
                return values
    raise RuntimeError("{} was not found in {}".format(marker, path))


