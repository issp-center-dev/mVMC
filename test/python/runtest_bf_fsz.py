def compare_child_rows(left, right, tolerance, label):
    if len(left) != len(right):
        print("ERROR: {} row count mismatch: left={} right={}".format(label, len(left), len(right)))
        return -1
    max_diff = 0.0
    for (li, lr, lii), (ri, rr, rii) in zip(left, right):
        if li != ri:
            print("ERROR: {} local index mismatch: left={} right={}".format(label, li, ri))
            return -1
        max_diff = max(max_diff, abs(lr - rr), abs(lii - rii))
    if max_diff > tolerance:
        print("ERROR: {} mismatch: max_abs_diff={:.3e}".format(label, max_diff))
        return -1
    return 0


def max_abs_diff(left_rows, right_rows):
    if len(left_rows) != len(right_rows):
        raise RuntimeError("row count mismatch: left={} right={}".format(len(left_rows), len(right_rows)))
    max_diff = 0.0
    for left, right in zip(left_rows, right_rows):
        if len(left) != len(right):
            raise RuntimeError("column count mismatch: left={} right={}".format(len(left), len(right)))
        for x, y in zip(left, right):
            max_diff = max(max_diff, abs(x-y))
    return max_diff


def prepare_case(rootdir, name, include_backflow, orbital_complex_type=1,
                 orbital_optimize=True, backflow_optimize=False):
    refdir = os.path.join(rootdir, "data", "BackFlow_Identity_Complex")
    workdir = os.path.join(rootdir, "work", name)
    if os.path.exists(workdir):
        shutil.rmtree(workdir)
    os.makedirs(workdir)

    copy_base_defs(refdir, workdir)
    write_namelist(workdir, include_backflow)
    write_orbital_general(
        workdir,
        nsite=4,
        complex_type=orbital_complex_type,
        optimize=orbital_optimize,
    )
    write_green_defs(workdir)
    if include_backflow:
        write_chain_nn_backflow(workdir, length=4, optimize=backflow_optimize)
    return workdir


def run_twobody_stale_base_case(rootdir, case_name, mpi_procs=None):
    pf_update_cases = {
        "BackFlow_FSZ_PfUpdate_NonIdentity_Complex": "optimized",
        "BackFlow_FSZ_PfUpdate_NonIdentity_Complex_mpi": "optimized",
        "BackFlow_FSZ_PfUpdate_MoreRanks_NonIdentity_Complex_mpi": "optimized",
        "BackFlow_FSZ_PfUpdate_Fallback_NonIdentity_Complex": "fallback",
        "BackFlow_FSZ_PfUpdate_ExactZeroFallback_NonIdentity_Complex": "exact-zero",
        "BackFlow_FSZ_PfUpdate_LapackFallback_NonIdentity_Complex": "lapack",
        "BackFlow_FSZ_PfUpdate_DirectFull_NonIdentity_Complex": "direct-full",
        "BackFlow_FSZ_PfUpdate_PermutedLabels_NonIdentity_Complex": "permuted",
        "BackFlow_FSZ_PfUpdate_ExplicitState_NonIdentity_Complex": "explicit-state",
        "BackFlow_FSZ_PfUpdate_InvalidArguments_NonIdentity_Complex": "arguments",
    }
    affected_cases = (
        "BackFlow_FSZ_AffectedRows_NonIdentity_Complex",
        "BackFlow_FSZ_AffectedRows_NonIdentity_Complex_mpi",
    ) + tuple(pf_update_cases)
    if case_name != "BackFlow_FSZ_TwoBodyG_StaleBase_NonIdentity_Complex" \
            and case_name not in affected_cases:
        return None

    general_rows, contracted_rows = build_stale_base_two_body_rows()
    ordered_rows = general_rows + contracted_rows
    reference_rows = contracted_rows + general_rows
    reference_case_rows = reference_rows
    if case_name in pf_update_cases and pf_update_cases[case_name] == "permuted":
        reference_case_rows = ordered_rows

    ordered_workdir = prepare_case(rootdir, case_name, True)
    reference_workdir = prepare_case(rootdir, case_name + "_reference", True)
    for workdir, rows in (
        (ordered_workdir, ordered_rows),
        (reference_workdir, reference_case_rows),
    ):
        update_modpara(workdir, {"NVMCSample": "1"})
        if case_name in affected_cases:
            update_modpara(workdir, {"NMPTrans": "2"})
            make_momentum_projection(workdir)
        write_two_body_rows(workdir, rows)

    ordered_init = write_nonidentity_init(ordered_workdir)
    reference_init = write_nonidentity_init(reference_workdir)
    ordered_env = {
        "MVMC_BF_FSZ_GREEN_REBUILD_CHECK": "1",
        "MVMC_BF_FSZ_AFFECTED_CHECK": "1",
        "MVMC_BF_PROFILE": "1",
    }
    if case_name in pf_update_cases:
        ordered_env["MVMC_BF_FSZ_PF_UPDATE_CHECK"] = "1"
        if pf_update_cases[case_name] == "fallback":
            ordered_env["MVMC_BF_FSZ_PF_UPDATE_FORCE_FALLBACK"] = "1"
        elif pf_update_cases[case_name] == "exact-zero":
            ordered_env["MVMC_BF_FSZ_PF_UPDATE_INJECT_STATUS"] = "1"
        elif pf_update_cases[case_name] == "lapack":
            ordered_env["MVMC_BF_FSZ_PF_UPDATE_INJECT_STATUS"] = "2"
        elif pf_update_cases[case_name] == "direct-full":
            ordered_env["MVMC_BF_FSZ_PF_UPDATE_KFULL"] = "1"
        elif pf_update_cases[case_name] == "permuted":
            ordered_env["MVMC_BF_FSZ_PERMUTE_PARTICLE_LABELS"] = "1"
        elif pf_update_cases[case_name] == "explicit-state":
            ordered_env["MVMC_BF_FSZ_PF_UPDATE_EXPLICIT_STATE_CHECK"] = "1"
        elif pf_update_cases[case_name] == "arguments":
            ordered_env["MVMC_BF_FSZ_PF_UPDATE_ARGUMENT_CHECK"] = "1"
    ordered_proc = run_vmc(
        rootdir,
        ordered_workdir,
        mpi_procs=mpi_procs,
        init_path=ordered_init,
        extra_env=ordered_env,
    )
    if ordered_proc.returncode != 0:
        print(ordered_proc.stdout)
        return ordered_proc.returncode

    reference_env = None
    if case_name in pf_update_cases and pf_update_cases[case_name] == "permuted":
        reference_env = {
            "MVMC_BF_FSZ_PERMUTE_PARTICLE_LABELS": "1",
            "MVMC_BF_FSZ_PF_UPDATE_KFULL": "1",
        }
    reference_proc = run_vmc(
        rootdir,
        reference_workdir,
        mpi_procs=mpi_procs,
        init_path=reference_init,
        extra_env=reference_env,
    )
    if reference_proc.returncode != 0:
        print(reference_proc.stdout)
        return reference_proc.returncode

    timer_path = os.path.join(ordered_workdir, "output", "zvo_CalcTimer.dat")
    for source in ("sample", "green"):
        changed_calls, changed_mean, changed_max = read_bffsz_profile_stats(
            timer_path, source, "changed")
        affected_calls, affected_mean, affected_max = read_bffsz_profile_stats(
            timer_path, source, "affected")
        if changed_calls <= 0 or affected_calls != changed_calls:
            print("ERROR: BF-FSZ {} affected profile call mismatch".format(source))
            return -1
        if changed_mean <= 0.0 or changed_max <= 0 or changed_max > 8:
            print("ERROR: BF-FSZ {} changed profile is invalid".format(source))
            return -1
        if affected_mean < 1.0 or affected_max < 1 or affected_max > 4:
            print("ERROR: BF-FSZ {} affected profile is invalid".format(source))
            return -1
        for hist_kind in ("changed hist", "affected hist", "affected ratio hist"):
            if read_bffsz_profile_hist_sum(timer_path, source, hist_kind) != changed_calls:
                print("ERROR: BF-FSZ {} {} count mismatch".format(source, hist_kind))
                return -1

        if case_name in pf_update_cases:
            paths = read_bffsz_pf_paths(timer_path, source)
            mode = pf_update_cases[case_name]
            if mode in ("optimized", "permuted", "explicit-state", "arguments"):
                if paths["optimized"] <= 0 or paths["fallback"] != 0:
                    print("ERROR: BF-FSZ {} optimized Pfaffian path was not isolated".format(source))
                    return -1
            elif mode in ("fallback", "exact-zero", "lapack"):
                if paths["fallback"] <= 0 or paths["optimized"] != 0:
                    print("ERROR: BF-FSZ {} fallback Pfaffian path was not isolated".format(source))
                    return -1
            elif mode == "direct-full":
                if paths["direct-full"] <= 0 or paths["optimized"] != 0 \
                        or paths["fallback"] != 0:
                    print("ERROR: BF-FSZ {} direct-full Pfaffian path was not isolated".format(source))
                    return -1

    if case_name in pf_update_cases and pf_update_cases[case_name] == "permuted":
        return assert_finite_nonzero_rows(
            os.path.join(ordered_workdir, "output", "zvo_cisajs_001.dat"),
            "permuted-label Pfaffian update",
        )

    ordered_path = os.path.join(ordered_workdir, "output", "zvo_cisajscktalt_001.dat")
    reference_path = os.path.join(reference_workdir, "output", "zvo_cisajscktalt_001.dat")
    ordered_values = read_float_rows(ordered_path)
    reference_values = read_float_rows(reference_path)
    if len(ordered_values) != len(ordered_rows) or len(reference_values) != len(reference_rows):
        print("ERROR: stale-base TwoBodyG output row count mismatch")
        return -1

    ordered_by_term = dict(zip(ordered_rows, ordered_values))
    reference_by_term = dict(zip(reference_case_rows, reference_values))
    diff = max_abs_diff(
        [ordered_by_term[row] for row in ordered_rows],
        [reference_by_term[row] for row in ordered_rows],
    )
    if diff > 1.0e-12:
        print("ERROR: BF-FSZ TwoBodyG depends on general/contracted term order: "
              "max_abs_diff={:.3e}".format(diff))
        return -1

    return assert_finite_nonzero_rows(ordered_path, "stale-base TwoBodyG")


def run_sr_diff_case(rootdir, case_name, mpi_procs=None):
    sr_diff_cases = {
        "BackFlow_FSZ_SRDiff_Identity_Complex": (False, False, True),
        "BackFlow_FSZ_SRDiff_Identity_Complex_mpi": (False, False, True),
        "BackFlow_FSZ_SRDiff_MomentumProjection_Complex": (True, False, True),
        "BackFlow_FSZ_SRDiff_NonIdentity_Complex": (False, True, False),
        "BackFlow_FSZ_SRDiff_MomentumProjection_NonIdentity_Complex": (True, True, False),
    }
    if case_name not in sr_diff_cases:
        return None

    use_momentum, use_nonidentity, check_identity = sr_diff_cases[case_name]
    workdir = prepare_case(rootdir, case_name, True)
    update_modpara(workdir, {"NVMCSample": "1"})
    if use_momentum:
        update_modpara(workdir, {"NMPTrans": "2"})
        make_momentum_projection(workdir)
    init_path = write_nonidentity_init(workdir) if use_nonidentity else None
    dump_path = os.path.join(workdir, "bf_fsz_sr_diff.dat")
    proc = run_vmc(
        rootdir,
        workdir,
        mpi_procs=mpi_procs,
        init_path=init_path,
        extra_env={"MVMC_BF_FSZ_SR_DIFF_DUMP": dump_path},
    )
    if proc.returncode != 0:
        print(proc.stdout)
        return proc.returncode
    if not os.path.exists(dump_path):
        print("ERROR: BF-FSZ SR diff dump was not created")
        return -1

    values = read_key_values(dump_path)
    if get_int(values, "info_bf") != 0:
        print("ERROR: BF-FSZ SR diff base calculation failed")
        return -1
    if get_int(values, "fd_fail_count") != 0:
        print("ERROR: BF-FSZ SR diff finite differences failed")
        print(open(dump_path).read())
        return -1
    if get_int(values, "nan_count") != 0:
        print("ERROR: BF-FSZ SR diff dump contains non-finite values")
        print(open(dump_path).read())
        return -1
    if get_int(values, "nonzero_projbf_fd_count") <= 0:
        print("ERROR: BF-FSZ ProjBF finite difference was vacuous")
        print(open(dump_path).read())
        return -1
    if get_int(values, "nonzero_orbital_fd_count") <= 0:
        print("ERROR: BF-FSZ orbital finite difference was vacuous")
        print(open(dump_path).read())
        return -1

    projbf_diff = get_float(values, "max_abs_projbf_fd_diff")
    orbital_diff = get_float(values, "max_abs_orbital_fd_diff")
    if projbf_diff > 1.0e-8:
        print("ERROR: BF-FSZ ProjBF finite-difference mismatch: {:.3e}".format(projbf_diff))
        print(open(dump_path).read())
        return -1
    if orbital_diff > 1.0e-8:
        print("ERROR: BF-FSZ orbital finite-difference mismatch: {:.3e}".format(orbital_diff))
        print(open(dump_path).read())
        return -1
    if check_identity:
        if get_int(values, "info_no_bf") != 0:
            print("ERROR: BF-FSZ SR diff NoBF reference calculation failed")
            print(open(dump_path).read())
            return -1
        identity_diff = get_float(values, "max_abs_identity_orbital_diff")
        if identity_diff > 1.0e-10:
            print("ERROR: BF-FSZ identity orbital O mismatch: {:.3e}".format(identity_diff))
            print(open(dump_path).read())
            return -1
    return 0


def optimization_modpara_updates(nstore=0, nsrcg=0, nsplit=1, samples=16):
    updates = {
        "NVMCCalMode": "0",
        "NSROptItrStep": "2",
        "NSROptItrSmp": "2",
        "NVMCSample": str(samples),
        "NVMCWarmUp": "4",
        "DSROptRedCut": "1.0e-10",
        "DSROptStaDel": "1.0e-2",
        "DSROptStepDt": "1.0e-2",
        "NStore": str(nstore),
        "NSRCG": str(nsrcg),
        "NSplitSize": str(nsplit),
    }
    if nsrcg != 0:
        updates["NSRCGFallback"] = "1"
        updates["NSRCGAbortOnFail"] = "0"
    return updates


def prepare_optimization_case(rootdir, name, include_backflow=True, orbital_complex_type=1,
                              orbital_optimize=True, backflow_optimize=False,
                              momentum_projection=False, nstore=0, nsrcg=0,
                              nsplit=1, samples=16):
    workdir = prepare_case(
        rootdir,
        name,
        include_backflow,
        orbital_complex_type=orbital_complex_type,
        orbital_optimize=orbital_optimize,
        backflow_optimize=backflow_optimize,
    )
    update_modpara(workdir, optimization_modpara_updates(nstore, nsrcg, nsplit, samples))
    if momentum_projection:
        update_modpara(workdir, {"NMPTrans": "2"})
        make_momentum_projection(workdir)
    return workdir


def assert_optimization_outputs(workdir, include_backflow):
    zqp_path = os.path.join(workdir, "output", "zqp_opt.dat")
    if not os.path.exists(zqp_path):
        print("ERROR: zqp_opt.dat was not created.")
        return -1
    status = assert_finite_values(read_flat_floats(zqp_path), "zqp_opt.dat")
    if status != 0:
        return status

    nslater = parse_norbitalidx(os.path.join(workdir, "orbitalidxgen.def"))
    nprojbf = build_chain_nn_backflow(length=4, optimize=False).n_proj_bf if include_backflow else 0
    expected_zqp_groups = 2 + nprojbf + nslater
    zqp_values = read_flat_floats(zqp_path)
    if len(zqp_values) != 3 * expected_zqp_groups:
        print("ERROR: zqp_opt.dat length mismatch: got {} values, expected {}".format(
            len(zqp_values), 3 * expected_zqp_groups))
        return -1
    if include_backflow:
        status = assert_child_opt_file(
            workdir,
            "zqp_bf_opt.dat",
            nprojbf,
            2,
            "ProjBF opt block",
        )
        if status != 0:
            return status
    return assert_child_opt_file(
        workdir,
        "zqp_orbital_general_opt.dat",
        nslater,
        2 + nprojbf,
        "OrbitalGeneral opt block",
    )


def run_positive_optimization_case(rootdir, case_name, mpi_procs, options):
    prep_options = dict(options)
    prep_options.pop("compare_no_bf", None)
    prep_options.pop("compare_direct_bf", None)
    workdir = prepare_optimization_case(rootdir, case_name, **prep_options)
    proc = run_vmc(rootdir, workdir, mpi_procs)
    if proc.returncode != 0:
        print(proc.stdout)
        return proc.returncode
    status = assert_optimization_outputs(workdir, include_backflow=True)
    if status != 0:
        return status

    if options.get("compare_no_bf", False):
        no_bf_options = dict(options)
        no_bf_options.pop("compare_no_bf", None)
        no_bf_options.pop("compare_direct_bf", None)
        no_bf_options["include_backflow"] = False
        no_bf_options["backflow_optimize"] = False
        no_bf_workdir = prepare_optimization_case(
            rootdir,
            case_name + "_nobf_opt_ref",
            **no_bf_options
        )
        no_bf_proc = run_vmc(rootdir, no_bf_workdir, mpi_procs)
        if no_bf_proc.returncode != 0:
            print(no_bf_proc.stdout)
            return no_bf_proc.returncode
        status = assert_optimization_outputs(no_bf_workdir, include_backflow=False)
        if status != 0:
            return status
        status = compare_child_rows(
            read_orbital_opt_rows(workdir),
            read_orbital_opt_rows(no_bf_workdir),
            1.0e-8,
            "BF-FSZ identity orbital optimization",
        )
        if status != 0:
            return status

    if options.get("compare_direct_bf", False):
        ref_options = dict(options)
        ref_options.pop("compare_no_bf", None)
        ref_options.pop("compare_direct_bf", None)
        ref_options["nstore"] = 0
        ref_options["nsrcg"] = 0
        ref_workdir = prepare_optimization_case(
            rootdir,
            case_name + "_direct_ref",
            **ref_options
        )
        ref_proc = run_vmc(rootdir, ref_workdir, mpi_procs)
        if ref_proc.returncode != 0:
            print(ref_proc.stdout)
            return ref_proc.returncode
        status = assert_optimization_outputs(ref_workdir, include_backflow=True)
        if status != 0:
            return status
        status = compare_child_rows(
            read_orbital_opt_rows(workdir),
            read_orbital_opt_rows(ref_workdir),
            1.0e-8,
            "stored-O BF-FSZ orbital optimization",
        )
        if status != 0:
            return status

    return 0


